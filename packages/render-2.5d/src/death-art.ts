const dither = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5]
export const deathDither = (x: number, y: number) => (dither[(y % 4) * 4 + x % 4] + 0.5) / 16

export function deathPixelColour(shade: number, colour: readonly [number, number, number], luminous = false): readonly [number, number, number] {
  if (shade === 5) return luminous ? [255, 255, 248] : [211, 183, 137]
  const scale = shade === 1 ? luminous ? 0.5 : 0.26 : shade === 2 ? 0.55 : shade === 4 ? 1.35 : 1
  return colour.map(c => Math.min(255, Math.round(c * scale))) as [number, number, number]
}
